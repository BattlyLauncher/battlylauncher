const fs = require('node:fs'),
  path = require('node:path');
const source = require('../resources/locales/interface-translations.json');
const dialogs = require('../resources/locales/dialog-translations.json');
const gameSettings = require('../resources/locales/game-settings-translations.json');
const englishDialogs = require('../resources/locales/dialog-english.json');
const englishReleaseKeys = require('../resources/locales/english-release-keys.json');
const runtimeSource = require('../resources/locales/runtime-source.json');
const corrections = require('../resources/locales/reviewed-corrections.json');
const sourceTranslations = require('../resources/locales/source-translations.json');
for (const entry of sourceTranslations.entries) {
  for (const language of source.languages) {
    if (!entry.translations[language]?.trim())
      throw Error(`Missing source translation: ${language}/${entry.source}`);
  }
}
fs.writeFileSync(
  path.resolve(__dirname, '../src/shared/i18n-source-aliases.ts'),
  '// Generated by build-language-packs.cjs. Static source aliases, never user data.\n' +
    'export const sourceAliases: ReadonlyArray<readonly [string, string]> = ' +
    JSON.stringify(
      sourceTranslations.entries
        .filter((entry) => entry.source !== entry.translations.es)
        .map((entry) => [entry.source, entry.translations.es]),
      null,
      2,
    ) +
    ';\n',
);
const complete = fs.existsSync(
  path.resolve(__dirname, '../resources/locales/complete-translations.json'),
)
  ? require('../resources/locales/complete-translations.json')
  : {};
const root = path.resolve(__dirname, '../src/renderer/i18n/locales');
const spanish = JSON.parse(fs.readFileSync(path.join(root, 'es.json'), 'utf8'));
const legacySpanish = require('../resources/locales/legacy-spanish.json').strings;
const normalize = (value) =>
  value
    .replace(/<br\s*\/?>/gi, ' ')
    .replace(/<[^>]+>/g, '')
    .replace(/[.!¡¿?…]+$/g, '')
    .replace(/\s+/g, ' ')
    .trim();
function migrateLegacy(sourceTree, target, dictionary) {
  for (const [key, value] of Object.entries(sourceTree)) {
    if (key === 'interface') continue;
    if (
      typeof value === 'string' &&
      dictionary.has(normalize(value)) &&
      typeof target[key] !== 'string'
    )
      target[key] = dictionary.get(normalize(value));
    else if (value && typeof value === 'object') {
      if (!target[key] || typeof target[key] !== 'object') target[key] = {};
      migrateLegacy(value, target[key], dictionary);
    }
  }
}
function overlay(sourceTree, target, dictionary) {
  for (const [key, value] of Object.entries(sourceTree)) {
    if (key === 'interface' || key === 'modalFallback') continue;
    if (typeof value === 'string' && dictionary.has(value.trim()))
      target[key] = dictionary.get(value.trim());
    else if (value && typeof value === 'object') {
      target[key] ??= {};
      overlay(value, target[key], dictionary);
    }
  }
}
function fillMissing(sourceTree, target, dictionary) {
  for (const [key, value] of Object.entries(sourceTree)) {
    if (typeof value === 'string') {
      if (
        (typeof target[key] !== 'string' || target[key] === value) &&
        dictionary[value] !== undefined
      )
        target[key] = dictionary[value];
    } else if (value && typeof value === 'object') {
      target[key] ??= {};
      fillMissing(value, target[key], dictionary);
    }
  }
}
for (const [index, language] of source.languages.entries()) {
  const file = path.join(root, `${language}.json`);
  const data = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (complete[language]) fillMissing(spanish, data, complete[language]);
  const legacy = new Map();
  for (const [key, original] of Object.entries(legacySpanish)) {
    const translated = data.strings?.[key];
    if (typeof translated === 'string' && typeof original === 'string' && translated !== original)
      legacy.set(
        normalize(original),
        translated.replace(/<br\s*\/?>/gi, '\n').replace(/<[^>]+>/g, ''),
      );
  }
  migrateLegacy(spanish, data, legacy);
  data.interface = Object.fromEntries(
    source.rows.map((row, key) => {
      if (row.length !== source.languages.length || !row[index])
        throw new Error(`Missing translation: ${language}/${key}`);
      return [`text${key}`, row[index]];
    }),
  );
  overlay(spanish, data, new Map(source.rows.map((row) => [row[0], row[index]])));
  data.gameSettings = Object.fromEntries(
    gameSettings.rows.map((row, key) => [`text${key}`, row[index]]),
  );
  data.modalCopy = Object.fromEntries(
    dialogs.rows.map((row, key) => {
      if (row.length !== dialogs.languages.length || !row[index])
        throw Error(`Missing dialog translation: ${language}/${key}`);
      const placeholders = (text) =>
        [...text.matchAll(/\{\d+\}/g)]
          .map((match) => match[0])
          .sort()
          .join(',');
      if (placeholders(row[0]) !== placeholders(row[index]))
        throw Error(`Invalid placeholders: ${language}/${key}`);
      return [`text${key}`, row[index]];
    }),
  );
  // Keyed labels and sentence translation must use the same reviewed copy.
  overlay(
    spanish,
    data,
    new Map(
      [...source.rows, ...dialogs.rows, ...gameSettings.rows].map((row) => [row[0], row[index]]),
    ),
  );
  if (language === 'es' || language === 'en') {
    data.modalFallback = Object.fromEntries(
      Object.entries(englishDialogs).map(([es, en], key) => [
        `text${key}`,
        language === 'es' ? es : en,
      ]),
    );
  } else {
    data.modalFallback ??= {};
    for (const [index, text] of Object.keys(englishDialogs).entries()) {
      const key = `text${index}`;
      const translated = complete[language]?.[text];
      if (translated !== undefined) data.modalFallback[key] ??= translated;
    }
  }
  if (language === 'en') {
    const reviewed = new Map(
      [...source.rows, ...dialogs.rows, ...gameSettings.rows].map((row) => [row[0], row[1]]),
    );
    for (const [es, en] of Object.entries(englishDialogs)) reviewed.set(es, en);
    overlay(spanish, data, reviewed);
    for (const [key, value] of Object.entries(englishReleaseKeys)) {
      const parts = key.split('.');
      const leaf = parts.pop();
      let target = data;
      for (const part of parts) target = target[part] ??= {};
      target[leaf] = value;
    }
  }
  data.version = corrections.revision;
  data.sourceCopy = Object.fromEntries(
    sourceTranslations.entries.map((entry, index) => [
      `text${index}`,
      entry.translations[language],
    ]),
  );
  data.runtimeCopy = Object.fromEntries(
    runtimeSource.map((text, index) => {
      const translated = language === 'es' ? text : complete[language]?.[text];
      if (translated === undefined) throw Error(`Missing runtime translation: ${language}/${text}`);
      return [`text${index}`, translated];
    }),
  );
  data.reviewedCopy = Object.fromEntries(
    corrections.rows.map((row, rowIndex) => {
      if (row.length !== source.languages.length || !row[index])
        throw Error(`Invalid reviewed row ${rowIndex}`);
      return [`text${rowIndex}`, row[index]];
    }),
  );
  // Apply reviewed sentences to every keyed alias, including legacy keys. A full
  // key count alone does not catch partly translated strings or obsolete aliases.
  const plain = (text) =>
    text
      .replace(/<br\s*\/?>/gi, ' ')
      .replace(/<[^>]*>/g, '')
      .replace(/\s+/g, ' ')
      .trim();
  const reviewed = new Map();
  for (const row of [...source.rows, ...dialogs.rows, ...gameSettings.rows]) {
    if (!reviewed.has(plain(row[0]))) reviewed.set(plain(row[0]), plain(row[index]));
  }
  for (const row of corrections.rows) reviewed.set(plain(row[0]), plain(row[index]));
  if (language === 'en')
    for (const [key, value] of Object.entries(corrections.englishKeys)) {
      let original = spanish;
      for (const part of key.split('.')) original = original?.[part];
      if (typeof original === 'string') reviewed.set(plain(original), value);
    }
  function review(tree, original) {
    for (const [key, value] of Object.entries(tree)) {
      const sourceText = original?.[key];
      if (typeof value === 'string' && typeof sourceText === 'string') {
        const replacement = reviewed.get(plain(sourceText));
        if (replacement !== undefined && language !== 'es') tree[key] = replacement;
        if (language !== 'es' && sourceText.includes('Battly Worlds')) {
          for (const pattern of corrections.productPatterns[language] ?? [])
            tree[key] = tree[key].replace(new RegExp(pattern, 'gi'), 'Battly Worlds');
        }
      } else if (value && typeof value === 'object')
        review(value, key === 'strings' ? legacySpanish : original?.[key]);
    }
  }
  review(data, {
    ...spanish,
    reviewedCopy: Object.fromEntries(
      corrections.rows.map((row, index) => [`text${index}`, row[0]]),
    ),
  });
  // Repair keyed aliases too, including English diagnostic copy in the Spanish
  // catalogue. Use the original snapshot rather than already translated values.
  overlay(
    spanish,
    data,
    new Map(
      sourceTranslations.entries.flatMap((entry) => [
        [entry.source.trim(), entry.translations[language]],
        [entry.translations.es.trim(), entry.translations[language]],
      ]),
    ),
  );
  // Indexed source sentences are authoritative; old indexed snapshots must not
  // rewrite a new row through an obsolete alias or different capitalization.
  data.sourceCopy = Object.fromEntries(
    sourceTranslations.entries.map((entry, index) => [
      `text${index}`,
      entry.translations[language],
    ]),
  );
  fs.writeFileSync(file, JSON.stringify(data, null, 2) + '\n');
}
console.log(`Updated ${source.languages.length} locale packs.`);
